
from database.postgres_connection import get_postgres_connection


table_queries = [

    # 1. Users
    """
    CREATE TABLE IF NOT EXISTS users (
        user_id BIGINT PRIMARY KEY,
        username TEXT UNIQUE,
        first_name TEXT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
        last_seen_at TEXT,
        is_banned SMALLINT DEFAULT 0
            CHECK (is_banned IN (0, 1))
    )
    """,

    # 2. Contents
    """
    CREATE TABLE IF NOT EXISTS contents (
        content_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT,
        body TEXT,
        content_type TEXT DEFAULT 'poem'
            CHECK (content_type IN (
                'poem', 'reflection', 'lyrics', 'short_story'
            )),
        author_name TEXT,
        source TEXT,
        category TEXT DEFAULT 'love'
            CHECK (category IN (
                'love', 'nature', 'philosophy', 'life_lesson'
            )),
        submitted_by BIGINT NOT NULL,
        approved_by BIGINT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
        published_at TEXT,
        is_published SMALLINT DEFAULT 0
            CHECK (is_published IN (0, 1)),
        status TEXT DEFAULT 'pending'
            CHECK (status IN ('pending', 'approved', 'rejected')),

        UNIQUE (title, body),

        FOREIGN KEY (submitted_by)
            REFERENCES users(user_id)
            ON UPDATE CASCADE,

        FOREIGN KEY (approved_by)
            REFERENCES users(user_id)
            ON UPDATE CASCADE
    )
    """,

    # 3. Favorites
    """
    CREATE TABLE IF NOT EXISTS favourite (
        user_id BIGINT,
        content_id BIGINT,
        saved_at TEXT DEFAULT CURRENT_TIMESTAMP::text,

        PRIMARY KEY (user_id, content_id),

        FOREIGN KEY (user_id)
            REFERENCES users(user_id)
            ON UPDATE CASCADE ON DELETE CASCADE,

        FOREIGN KEY (content_id)
            REFERENCES contents(content_id)
            ON UPDATE CASCADE ON DELETE CASCADE
    )
    """,

    # 4. Submissions
    """
    CREATE TABLE IF NOT EXISTS submissions (
        submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        submitted_by BIGINT NOT NULL,
        title TEXT NOT NULL,
        body TEXT NOT NULL,
        content_type TEXT NOT NULL
            CHECK (content_type IN (
                'poem', 'reflection', 'lyrics', 'short_story'
            )),
        author_name TEXT,
        source TEXT,
        category TEXT,
        status TEXT NOT NULL DEFAULT 'pending'
            CHECK (status IN ('pending', 'approved', 'rejected')),
        reviewed_by BIGINT,
        reviewed_at TEXT,
        review_note TEXT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,
        content_id BIGINT UNIQUE,

        FOREIGN KEY (submitted_by)
            REFERENCES users(user_id)
            ON UPDATE CASCADE ON DELETE CASCADE,

        FOREIGN KEY (reviewed_by)
            REFERENCES users(user_id)
            ON UPDATE CASCADE ON DELETE SET NULL,

        FOREIGN KEY (content_id)
            REFERENCES contents(content_id)
            ON UPDATE CASCADE ON DELETE SET NULL
    )
    """,

    # 5. Bot roles
    """
    CREATE TABLE IF NOT EXISTS bot_roles (
        user_id BIGINT NOT NULL,
        role TEXT NOT NULL
            CHECK (role IN ('admin', 'moderator')),
        granted_by BIGINT,
        granted_at TEXT DEFAULT CURRENT_TIMESTAMP::text,

        PRIMARY KEY (user_id, role),

        FOREIGN KEY (user_id)
            REFERENCES users(user_id)
            ON UPDATE CASCADE ON DELETE CASCADE,

        FOREIGN KEY (granted_by)
            REFERENCES users(user_id)
            ON UPDATE CASCADE ON DELETE SET NULL
    )
    """,

    # 6. Groups
    """
    CREATE TABLE IF NOT EXISTS groups (
        group_id BIGINT PRIMARY KEY,
        group_title TEXT NOT NULL,
        welcome_enabled SMALLINT DEFAULT 1
            CHECK (welcome_enabled IN (0, 1)),
        rules_text TEXT,
        moderation_enabled SMALLINT DEFAULT 1
            CHECK (moderation_enabled IN (0, 1)),
        added_at TEXT DEFAULT CURRENT_TIMESTAMP::text
    )
    """,

    # 7. Moderation logs
    """
    CREATE TABLE IF NOT EXISTS moderation_logs (
        log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        group_id BIGINT NOT NULL,
        moderator_id BIGINT NOT NULL,
        target_user_id BIGINT,
        action TEXT NOT NULL
            CHECK (action IN (
                'warn', 'ban', 'unban', 'delete_message'
            )),
        reason TEXT,
        message_id BIGINT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP::text,

        FOREIGN KEY (group_id)
            REFERENCES groups(group_id)
            ON UPDATE CASCADE ON DELETE CASCADE,

        FOREIGN KEY (moderator_id)
            REFERENCES users(user_id)
            ON UPDATE CASCADE ON DELETE CASCADE,

        FOREIGN KEY (target_user_id)
            REFERENCES users(user_id)
            ON UPDATE CASCADE ON DELETE SET NULL
    )
    """,

    # 8. Channel publications
    """
    CREATE TABLE IF NOT EXISTS channel_publications (
        publication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        content_id BIGINT NOT NULL,
        channel_id BIGINT NOT NULL,
        message_id BIGINT,
        status TEXT NOT NULL DEFAULT 'pending'
            CHECK (status IN ('pending', 'posted', 'failed', 'removed')),
        posted_at TEXT,
        last_synced_at TEXT,
        content_hash TEXT,
        last_error TEXT,

        FOREIGN KEY (content_id)
            REFERENCES contents(content_id)
            ON DELETE CASCADE,

        UNIQUE (content_id, channel_id)
    )
    """
]


def initialize_postgres_db():
    with get_postgres_connection() as connection:
        for query in table_queries:
            connection.execute(query)
